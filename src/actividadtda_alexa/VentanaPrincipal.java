    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try{
            // datos
            String nombre = txtNombre.getText();
            double peso = Double.parseDouble(txtPeso.getText());
            String raza = txtRaza.getText();
            int edad = Integer.parseInt(txtEdad.getText());
            
            //Crear un gato
            Gato miGato = new Gato(nombre, peso, raza, edad);
            
            //Calcular la dosis diaria
            double dosisDiaria = miGato.calcularDosisMedicina();
            
            // Calcular la dosis para 5 días 
            double dosis5Dias = miGato.calcularDosisRecursiva(5);
            
            //Calcular edad humana y si es senior (gato abuedito)
            int edadHumana = miGato.calcularEdadHumana();
            boolean esSenior = miGato.esGatoSenior();
            
            areaResultados.setText("CALCULOS PARA " + miGato.getNombre() + "\n");
            areaResultados.append("Dosis diaria: " + dosisDiaria + " ml\n");
            areaResultados.append("Dosis para 5 días: " + dosis5Dias + " ml\n");
            areaResultados.append("Edad humana: " + edadHumana + " años\n");
            areaResultados.append("¿Es gato senior?: " + (esSenior ? "Sí" : "No") + "\n");
        }
        catch (NumberFormatException e) {
            areaResultados.setText("Error: En 'Peso' y 'Edad' debes escribir números.");
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

