    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // Se ejecuta al picar "Registrar Gato"
        try {
            //Leer datos de las cajas
            String nombre = txtNombre.getText();
            double peso = Double.parseDouble(txtPeso.getText());
            String raza = txtRaza.getText();
            int edad = Integer.parseInt(txtEdad.getText());

            //Crear al Gato
            Gato miGato = new Gato(nombre, peso, raza, edad);

            //Mostrar los datos en el área de resultados
            areaResultados.setText("GATO REGISTRADO\n");
            areaResultados.append("Nombre: " + miGato.getNombre() + "\n");
            areaResultados.append("Peso: " + miGato.getPeso() + " kg\n");
            areaResultados.append("Raza: " + miGato.getRaza() + "\n");
            areaResultados.append("Edad: " + miGato.getEdad() + " años\n");

            } catch (NumberFormatException e) {
            // Si el usuario escribe letras en peso o edad, mostramos un error
              areaResultados.setText("Error: En 'Peso' y 'Edad' debes escribir números.");
            }
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

